<?php

/**
 * تَوان | Tavaan — Demo Bootstrap (v0.0.1)
 *
 * نقطهٔ ورود اپلیکیشن نمایشی تَوان.
 *
 * زنجیره:
 *   ۱) ثابت‌ها
 *   ۲) core/bootstrap.php (Autoloader)
 *   ۳) مسیرهای Demo (engine-core, App)
 *   ۴) .env
 *   ۵) کشف و بارگذاری پیکربندی موتورها → config/engine.php
 */

declare(strict_types=1);

// ── ۱) مسیر ریشه ──────────────────────────────────────────────────────────
// نکته: __DIR__ در این فایل، خودِ ریشهٔ پروژه است (نه پدر آن).
// خطای قبلی: dirname(__DIR__) مسیر پدر پروژه را می‌داد که باعث می‌شد autoloader
// نتواند فایل‌ها را بیابد. اصلاح: استفاده از __DIR__ به‌جای dirname(__DIR__).
if (!defined('TVN_BASE_PATH')) {
    define('TVN_BASE_PATH', __DIR__);
}

// ── ۲) بارگذاری هستهٔ فریمورک ──────────────────────────────────────────────
require __DIR__ . '/core/bootstrap.php';

// ── ۳) اصلاح مسیرهای Demo ─────────────────────────────────────────────────
use Tavaan\Core\Autoloading\AutoloaderRegistry;

$autoloader = AutoloaderRegistry::get();

// Engine-Core در engine-core/ (نه vendor/)
$autoloader->addNamespace('Tavaan\\EngineCore\\', 'engine-core/');

// namespace اپلیکیشن
$autoloader->addNamespace('App\\', 'app/src/');

// ── ۴) بارگذاری .env ──────────────────────────────────────────────────────
$envFile = TVN_BASE_PATH . '/.env';
if (is_file($envFile) && is_readable($envFile)) {
    foreach (file($envFile, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES) ?: [] as $line) {
        $line = trim($line);
        if ($line === '' || str_starts_with($line, '#')) continue;
        if (str_contains($line, '=')) {
            [$key, $value] = explode('=', $line, 2);
            $key = trim($key);
            $value = trim($value);
            if (strlen($value) >= 2 && ($value[0] === '"' || $value[0] === "'") && $value[0] === substr($value, -1)) {
                $value = substr($value, 1, -1);
            }
            if (!isset($_SERVER[$key]) && !isset($_ENV[$key])) {
                $_SERVER[$key] = $value;
                $_ENV[$key] = $value;
            }
        }
    }
}

// ── ۵) کشف و بارگذاری پیکربندی موتورها ────────────────────────────────────
// هر موتور می‌تواند فایل config/<engine>.php داشته باشد.
// این فایل‌ها کشف و در config/engine.php به‌صورت واحد merge می‌شوند.
$enginesPath = TVN_BASE_PATH . '/engines';
$engineConfigs = [];

if (is_dir($enginesPath)) {
    foreach (new \DirectoryIterator($enginesPath) as $entry) {
        if ($entry->isDot() || !$entry->isDir()) continue;

        $engineId = $entry->getFilename();
        $engineDir = $entry->getPathname();

        // کشف فایل پیکربندی موتور: engines/<id>/config/<id>.php
        $configFile = $engineDir . '/config/' . $engineId . '.php';
        if (is_file($configFile) && is_readable($configFile)) {
            $config = require $configFile;
            if (is_array($config)) {
                $engineConfigs[$engineId] = $config;
            }
        }

        // همچنین بررسی config/config.php (برای موتورهایی با نام متفاوت)
        $altConfigFile = $engineDir . '/config/config.php';
        if (!isset($engineConfigs[$engineId]) && is_file($altConfigFile) && is_readable($altConfigFile)) {
            $config = require $altConfigFile;
            if (is_array($config)) {
                $engineConfigs[$engineId] = $config;
            }
        }
    }
}

// ذخیرهٔ پیکربندی یکپارچه موتورها در config/engine.php (در صورت نیاز)
$engineConfigPath = TVN_BASE_PATH . '/config/engine.php';
if (!empty($engineConfigs)) {
    // ذخیره به‌صورت فایل PHP (cache)
    $cacheContent = "<?php\n\n// Auto-generated by bootstrap.php — do not edit manually.\n// Merged engine configurations from engines/*/config/*.php\n\nreturn " . var_export($engineConfigs, true) . ";\n";
    file_put_contents($engineConfigPath, $cacheContent);
}

// بارگذاری پیکربندی یکپارچه
$GLOBALS['tvn_engine_configs'] = $engineConfigs;

return $autoloader;
